type StudentSeed = Omit<TeacherStudentRow, 'details'> & {
  details?: Partial<TeacherStudentDetails>;
};

function lastNameOf(fullName: string): string {
  const parts = fullName.trim().split(/\s+/);
  return parts[parts.length - 1] ?? fullName;
}

function buildDetails(
  seed: StudentSeed,
  extras?: Partial<TeacherStudentDetails>,
): TeacherStudentDetails {
  const surname = lastNameOf(seed.fullName);
  const isFemale = ['Maria', 'Ana', 'Sofia', 'Isabella', 'Camille', 'Hannah'].some((n) =>
    seed.fullName.startsWith(n),
  );
  const fatherFirst = isFemale ? 'Roberto' : 'Ramon';
  const motherFirst = isFemale ? 'Elena' : 'Maria';

  return {
    gender: isFemale ? 'Female' : 'Male',
    birthDate: extras?.birthDate ?? 'March 14, 2013',
    age: extras?.age ?? 13,
    address:
      extras?.address ??
      `123 Mabini St., Brgy. San Jose, ${seed.gradeLevel.includes('10') ? 'Makati' : 'Quezon City'}`,
    enrollmentDate: extras?.enrollmentDate ?? 'June 2, 2026',
    lrn: extras?.lrn ?? `1${seed.idNumber.replace(/-/g, '')}`.padEnd(12, '0').slice(0, 12),
    guardians: extras?.guardians ?? [
      {
        name: `${fatherFirst} ${surname}`,
        relationship: 'Father',
        phone: seed.phone.replace(/\d{3}$/, '111'),
        email: `${fatherFirst.toLowerCase()}.${surname.toLowerCase()}@email.com`,
        occupation: 'Engineer',
        isPrimary: true,
        appLinked: true,
      },
      {
        name: `${motherFirst} ${surname}`,
        relationship: 'Mother',
        phone: seed.phone.replace(/\d{3}$/, '222'),
        email: `${motherFirst.toLowerCase()}.${surname.toLowerCase()}@email.com`,
        occupation: 'Teacher',
        isLegalGuardian: true,
        appLinked: seed.status !== 'At Risk',
      },
    ],
    emergencyContact: extras?.emergencyContact ?? {
      name: `${fatherFirst} ${surname}`,
      relationship: 'Father',
      phone: seed.phone.replace(/\d{3}$/, '111'),
    },
    authorizedPickup: extras?.authorizedPickup ?? [
      {
        name: `${fatherFirst} ${surname}`,
        relationship: 'Father',
        phone: seed.phone.replace(/\d{3}$/, '111'),
      },
      {
        name: `${motherFirst} ${surname}`,
        relationship: 'Mother',
        phone: seed.phone.replace(/\d{3}$/, '222'),
      },
    ],
    allergies: extras?.allergies ?? 'None on file',
    medicalNotes: extras?.medicalNotes ?? 'No medical notes on file.',
    teacherNotes:
      extras?.teacherNotes ??
      (seed.status === 'At Risk'
        ? 'Monitor attendance and follow up with guardians this week.'
        : 'No special notes.'),
  };
}

function withDetails(seed: StudentSeed): TeacherStudentRow {
  const { details: extras, ...row } = seed;
  return {
    ...row,
    photoUrl: row.photoUrl ?? `https://i.pravatar.cc/150?u=eskwelahan-stu-${row.id}`,
    details: buildDetails(seed, extras),
  };
}

