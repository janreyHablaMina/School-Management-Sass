function sliceStudents(
  source: AttendanceStudentRow[],
  start: number,
  count: number,
  prefix: string
): AttendanceStudentRow[] {
  return source.slice(start, start + count).map((student, index) => ({
    ...student,
    id: `${prefix}-${index + 1}`,
  }));
}

